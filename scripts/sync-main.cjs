#!/usr/bin/env node
/**
 * sync-main: internal -> main, prepared for publishing.
 *   - starts from (and returns to) the internal branch, self-healing across
 *     crashed previous runs
 *   - main is reset --hard to internal, then internal-only content is
 *     stripped: docs/, vibe coding.md, README.public.md
 *   - README.md is replaced with README.public.md (product-page style)
 *
 * Usage: npm run sync-main          (merge + prepare, no push)
 *        npm run sync-main -- --push (merge + prepare + push origin main)
 */
const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

function git(args) {
  return execSync(`git ${args}`, { encoding: "utf8" });
}

function sh(cmd) {
  execSync(cmd, { stdio: "inherit" });
}

const root = path.resolve(__dirname, "..");

// 1. self-heal: make sure we start from a clean internal checkout
const startBranch = git("branch --show-current").trim();
if (startBranch !== "internal") {
  console.log(`current branch is '${startBranch}'; switching to internal...`);
  git("checkout internal");
}
const dirty = git("status --porcelain").trim();
if (dirty) {
  console.error("working tree is not clean; commit or stash first:\n" + dirty);
  process.exit(1);
}
const publicReadmePath = path.join(root, "README.public.md");
if (!fs.existsSync(publicReadmePath)) {
  console.error("README.public.md not found on internal; nothing to publish with.");
  process.exit(1);
}
// Read the public README into memory BEFORE switching branches (the file only
// exists on internal's working tree).
const publicReadmeContent = fs.readFileSync(publicReadmePath);

const shouldPush = process.argv.includes("--push");

// 2. point main at internal (main is fully derived; its extra commits are
//    regenerated by this script every run, so reset --hard is safe)
sh("git checkout main");
sh("git reset --hard internal");

// 3. strip internal-only content from main (index + working tree)
for (const item of ["docs", "vibe coding.md", "README.public.md"]) {
  const tracked = git(`ls-files "${item}"`).trim();
  if (tracked) {
    execSync(`git rm -r -q --cached "${item}"`, { stdio: "pipe" });
  }
  const fsPath = path.join(root, item);
  if (fs.existsSync(fsPath)) {
    fs.rmSync(fsPath, { recursive: true, force: true });
  }
}

// 4. install the public README
fs.writeFileSync(path.join(root, "README.md"), publicReadmeContent);
git("add README.md");

// 5. commit the preparation (amend if this is a re-run so main stays tidy)
const lastMessage = git("log -1 --pretty=%s").trim();
if (lastMessage === "chore: prepare public branch") {
  git('commit --amend -m "chore: prepare public branch"');
} else {
  git('commit -m "chore: prepare public branch"');
}

// 6. push. main is regenerated from internal every sync (reset --hard +
//    amended prepare commit), so the remote must be force-updated when the
//    amended hash diverges from a previously pushed main. --force-with-lease
//    refuses if someone else pushed in between. Sole-maintainer branch.
if (shouldPush) {
  sh("git push -u origin main --force-with-lease");
  console.log("pushed origin main (force-with-lease).");
} else {
  console.log("review with: git checkout main; then push with --force-with-lease.");
}

// 7. back to internal (restores docs/, internal README and README.public.md)
git("checkout internal");

console.log("\nmain is ready: docs/vibe coding stripped, public README installed.");
